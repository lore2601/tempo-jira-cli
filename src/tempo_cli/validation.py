"""Parsing and validation of user input: durations, dates, ranges, issue keys.

Arguments are often generated by AI agents, so every value that ends up in a
URL or request body is validated strictly.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from datetime import date, timedelta

from tempo_cli.errors import ValidationError

ISSUE_KEY_RE = re.compile(r"^[A-Z][A-Z0-9_]{0,49}-[1-9][0-9]{0,9}$")
PROJECT_KEY_RE = re.compile(r"^[A-Z][A-Z0-9_]{0,49}$")
ACCOUNT_ID_RE = re.compile(r"^[A-Za-z0-9:_-]{6,128}$")
ATTRIBUTE_KEY_RE = re.compile(r"^_?[A-Za-z0-9_.-]{1,100}_?$")
TIME_RE = re.compile(r"^([01]?[0-9]|2[0-3]):([0-5][0-9])(?::([0-5][0-9]))?$")
_DURATION_PART_RE = re.compile(r"(\d+(?:[.,]\d+)?)\s*(h|m|s)")
_CLOCK_DURATION_RE = re.compile(r"^(\d{1,3}):([0-5]\d)$")
_RELATIVE_DAYS_RE = re.compile(r"^([+-]?\d{1,4})d$")

MAX_WORKLOG_SECONDS = 24 * 3600
WEEKDAYS = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday"]


def _reject_control_chars(value: str, what: str) -> None:
    if any(unicodedata.category(ch) == "Cc" and ch not in "\n\t" for ch in value):
        raise ValidationError(f"{what} contains control characters")


# --------------------------------------------------------------------------- durations


def parse_duration(value: str, *, what: str = "duration", allow_zero: bool = False) -> int:
    """Parse ``1h30m``, ``1.5h``, ``90m``, ``1:30`` or ``3600s`` into seconds.

    A bare number such as ``2`` is ambiguous (hours or minutes?), so a unit is required.
    """
    raw = value.strip().lower().replace(" ", "")
    if not raw:
        raise ValidationError(f"Empty {what}")
    clock = _CLOCK_DURATION_RE.match(raw)
    if clock:
        seconds = int(clock.group(1)) * 3600 + int(clock.group(2)) * 60
    else:
        pos = 0
        seconds_f = 0.0
        for match in _DURATION_PART_RE.finditer(raw):
            if match.start() != pos:
                break
            amount = float(match.group(1).replace(",", "."))
            seconds_f += amount * {"h": 3600, "m": 60, "s": 1}[match.group(2)]
            pos = match.end()
        if pos != len(raw) or pos == 0:
            raise ValidationError(
                f"Invalid {what}: {value!r}",
                hint="Use forms like 1h30m, 1.5h, 90m, 1:30 (hours:minutes).",
            )
        seconds = round(seconds_f)
    if seconds < 0 or (seconds == 0 and not allow_zero):
        raise ValidationError(f"The {what} must be greater than zero")
    if seconds > MAX_WORKLOG_SECONDS:
        raise ValidationError(f"The {what} cannot exceed 24h")
    return seconds


def format_duration(seconds: int | None) -> str:
    """``5400`` → ``1h 30m``."""
    if seconds is None:
        return ""
    sign = "-" if seconds < 0 else ""
    seconds = abs(int(seconds))
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    parts = []
    if hours:
        parts.append(f"{hours}h")
    if minutes:
        parts.append(f"{minutes}m")
    if secs and not hours:
        parts.append(f"{secs}s")
    return sign + (" ".join(parts) or "0m")


def hours(seconds: int | None) -> float:
    return round((seconds or 0) / 3600, 2)


# --------------------------------------------------------------------------- dates


def parse_date(value: str, *, today: date | None = None) -> date:
    """Parse ``today``, ``yesterday``, ``-2d``, a weekday name or ``YYYY-MM-DD``.

    Weekday names refer to the most recent such day (today included).
    """
    today = today or date.today()
    raw = value.strip().lower()
    if raw in {"today", "oggi"}:
        return today
    if raw in {"yesterday", "ieri"}:
        return today - timedelta(days=1)
    rel = _RELATIVE_DAYS_RE.match(raw)
    if rel:
        return today + timedelta(days=int(rel.group(1)))
    if raw in WEEKDAYS:
        delta = (today.weekday() - WEEKDAYS.index(raw)) % 7
        return today - timedelta(days=delta)
    try:
        return date.fromisoformat(raw)
    except ValueError:
        raise ValidationError(
            f"Invalid date: {value!r}",
            hint="Use YYYY-MM-DD, today, yesterday, -2d, or a weekday name (monday).",
        ) from None


def parse_time(value: str) -> str:
    """Normalise ``9:30`` / ``09:30:00`` to ``HH:MM:SS``."""
    match = TIME_RE.match(value.strip())
    if not match:
        raise ValidationError(f"Invalid start time: {value!r}", hint="Use HH:MM, e.g. 09:30.")
    return f"{int(match.group(1)):02d}:{match.group(2)}:{match.group(3) or '00'}"


@dataclass(frozen=True)
class DateRange:
    start: date
    end: date

    def days(self) -> list[date]:
        return [self.start + timedelta(days=i) for i in range((self.end - self.start).days + 1)]


PERIODS = ("today", "yesterday", "week", "last-week", "month", "last-month")


def period_range(name: str, *, today: date | None = None) -> DateRange:
    today = today or date.today()
    if name == "today":
        return DateRange(today, today)
    if name == "yesterday":
        day = today - timedelta(days=1)
        return DateRange(day, day)
    if name in {"week", "last-week"}:
        monday = today - timedelta(days=today.weekday())
        if name == "last-week":
            monday -= timedelta(days=7)
        return DateRange(monday, monday + timedelta(days=6))
    if name in {"month", "last-month"}:
        first = today.replace(day=1)
        if name == "last-month":
            first = (first - timedelta(days=1)).replace(day=1)
        next_first = (first.replace(day=28) + timedelta(days=4)).replace(day=1)
        return DateRange(first, next_first - timedelta(days=1))
    raise ValidationError(f"Unknown period {name!r}", hint=f"Use one of: {', '.join(PERIODS)}")


def resolve_range(
    period: str | None,
    start: str | None,
    end: str | None,
    *,
    default: str = "week",
    today: date | None = None,
) -> DateRange:
    """Combine ``--period`` with explicit ``--from``/``--to``."""
    if period and (start or end):
        raise ValidationError("Use either a period or --from/--to, not both")
    if start or end:
        first = parse_date(start, today=today) if start else parse_date(end or "", today=today)
        last = parse_date(end, today=today) if end else (today or date.today())
        if last < first:
            raise ValidationError("--to is before --from")
        if (last - first).days > 366:
            raise ValidationError("Date ranges are limited to one year")
        return DateRange(first, last)
    return period_range(period or default, today=today)


# --------------------------------------------------------------------------- identifiers


def issue_key(value: str) -> str:
    key = value.strip().upper()
    if not ISSUE_KEY_RE.match(key):
        raise ValidationError(f"Invalid issue key: {value!r}", hint="Expected a key like PROJ-123.")
    return key


def is_issue_id(value: str) -> bool:
    return value.strip().isdigit()


def project_key(value: str) -> str:
    key = value.strip().upper()
    if not PROJECT_KEY_RE.match(key):
        raise ValidationError(f"Invalid project key: {value!r}", hint="Expected a key like PROJ.")
    return key


def account_id(value: str) -> str:
    value = value.strip()
    if not ACCOUNT_ID_RE.match(value):
        raise ValidationError(f"Invalid Atlassian account id: {value!r}")
    return value


def worklog_id(value: str) -> str:
    value = value.strip()
    if not value.isdigit() or len(value) > 19:
        raise ValidationError(f"Invalid Tempo worklog id: {value!r}", hint="Expected a number.")
    return value


def attribute(value: str) -> tuple[str, str]:
    """Parse ``KEY=VALUE`` for work attributes."""
    if "=" not in value:
        raise ValidationError(f"Invalid attribute {value!r}", hint="Use KEY=VALUE.")
    key, val = value.split("=", 1)
    key = key.strip()
    if not ATTRIBUTE_KEY_RE.match(key):
        raise ValidationError(f"Invalid attribute key: {key!r}")
    _reject_control_chars(val, "attribute value")
    return key, val.strip()


def description(value: str) -> str:
    _reject_control_chars(value, "description")
    if len(value) > 10_000:
        raise ValidationError("Description is too long (max 10000 characters)")
    return value
